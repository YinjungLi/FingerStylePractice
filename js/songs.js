export function normalizeTitle(s) {
  return (s || '').toLowerCase().replace(/[\s\-_'’"「」《》()（）.,!！?？]/g, '');
}

export function findInLibrary(query) {
  const q = normalizeTitle(query);
  if (!q) return null;
  for (const song of LIBRARY) {
    const names = [song.title, ...(song.aliases || [])].map(normalizeTitle);
    if (names.some((n) => n === q)) return song;
  }
  for (const song of LIBRARY) {
    const names = [song.title, ...(song.aliases || [])].map(normalizeTitle);
    if (names.some((n) => n.length >= 2 && (n.includes(q) || q.includes(n)))) return song;
  }
  return null;
}
